# =============================================================================
# Task 2: Predict Next Day's Closing Price Using Historical Stock Data
# =============================================================================
# Goal: Use yfinance to fetch Apple stock data, engineer features, and train
#       a Random Forest regressor to predict the next day's close price.
# =============================================================================

import pandas as pd
import numpy as np
import yfinance as yf
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error
from sklearn.model_selection import train_test_split
import matplotlib.pyplot as plt

# -----------------------------------------------------------------------------
# 1. Fetch historical data for Apple (AAPL)
# -----------------------------------------------------------------------------
def fetch_stock_data(ticker="AAPL", period="1y"):
    """
    Download stock data from Yahoo Finance.
    Parameters:
        ticker (str): Stock symbol.
        period (str): Time period (e.g., '1y', '6mo', '3mo').
    Returns:
        DataFrame with columns: Open, High, Low, Close, Volume.
    """
    stock = yf.Ticker(ticker)
    df = stock.history(period=period)
    if df.empty:
        raise ValueError(f"No data found for ticker {ticker}")
    print(f"Downloaded {len(df)} days of data for {ticker}")
    return df[['Open', 'High', 'Low', 'Close', 'Volume']]

df = fetch_stock_data(ticker="AAPL", period="1y")
print(df.head())

# -----------------------------------------------------------------------------
# 2. Feature engineering: use today's features to predict tomorrow's close
# -----------------------------------------------------------------------------
# Shift the target (Close) by -1 so that row i contains the next day's close
df['Target'] = df['Close'].shift(-1)
# Drop the last row (no target available)
df.dropna(inplace=True)

# Features: Open, High, Low, Volume (and maybe derived ones)
feature_cols = ['Open', 'High', 'Low', 'Volume']
X = df[feature_cols]
y = df['Target']

# -----------------------------------------------------------------------------
# 3. Train / test split (time‑series aware: do not shuffle)
# -----------------------------------------------------------------------------
split_idx = int(0.8 * len(X))
X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]

print(f"Training samples: {X_train.shape[0]}, Testing samples: {X_test.shape[0]}")

# -----------------------------------------------------------------------------
# 4. Train Random Forest Regressor
# -----------------------------------------------------------------------------
model = RandomForestRegressor(n_estimators=100, random_state=42, n_jobs=-1)
model.fit(X_train, y_train)

# -----------------------------------------------------------------------------
# 5. Predictions and evaluation
# -----------------------------------------------------------------------------
y_pred = model.predict(X_test)

mae = mean_absolute_error(y_test, y_pred)
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
print(f"\nTest set performance:")
print(f"MAE : ${mae:.2f}")
print(f"RMSE: ${rmse:.2f}")

# -----------------------------------------------------------------------------
# 6. Plot actual vs predicted closing prices
# -----------------------------------------------------------------------------
plt.figure(figsize=(12, 6))
plt.plot(y_test.index, y_test, label="Actual Close", color='blue', linewidth=2)
plt.plot(y_test.index, y_pred, label="Predicted Close", color='red', linestyle='--', linewidth=2)
plt.title("AAPL: Actual vs Predicted Next Day Closing Price", fontsize=14)
plt.xlabel("Date")
plt.ylabel("Price (USD)")
plt.legend()
plt.grid(alpha=0.3)
plt.savefig("task2_stock_prediction.png", dpi=150)
plt.show()